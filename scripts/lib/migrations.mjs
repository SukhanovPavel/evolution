import { readFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
export function migrationFiles() {
  return readdirSync("supabase/migrations")
    .filter((n) => /^\d+_.+\.sql$/.test(n))
    .sort()
    .map((name) => {
      const [version, ...parts] = name.slice(0, -4).split("_");
      const sql = readFileSync(`supabase/migrations/${name}`, "utf8");
      return {
        name,
        version,
        label: parts.join("_"),
        sql,
        checksum: createHash("sha256").update(sql).digest("hex"),
      };
    });
}
function literal(value) {
  return `'${value.replaceAll("'", "''")}'`;
}
function dollar(value, base) {
  let tag = base;
  while (value.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${value}$${tag}$`;
}
export function migrationBundle() {
  const files = migrationFiles();
  const parts = [
    `-- Generated by npm run db:prepare. No credentials or user records.\n-- Applies pending migrations and catalog seed atomically; keeps Supabase CLI history.\nbegin;\nselect pg_advisory_xact_lock(hashtextextended('evolution-schema-migration',0));\ncreate schema if not exists supabase_migrations;\ncreate table if not exists supabase_migrations.schema_migrations(version text primary key);\nalter table supabase_migrations.schema_migrations add column if not exists name text;\nalter table supabase_migrations.schema_migrations add column if not exists statements text[];\ncreate table if not exists supabase_migrations.evolution_checksums(version text primary key,checksum text not null);`,
  ];
  for (const m of files) {
    parts.push(
      `do $evolution_apply$ begin\n if exists(select 1 from supabase_migrations.evolution_checksums where version=${literal(m.version)} and checksum<>${literal(m.checksum)}) then raise exception 'Applied Evolution migration changed: ${m.name}';end if;\n if not exists(select 1 from supabase_migrations.schema_migrations where version=${literal(m.version)}) then\n execute ${dollar(m.sql, "evolution_sql")};\n insert into supabase_migrations.schema_migrations(version,name,statements) values(${literal(m.version)},${literal(m.label)},array[${dollar(m.sql, "evolution_source")}]);\n insert into supabase_migrations.evolution_checksums(version,checksum) values(${literal(m.version)},${literal(m.checksum)}) on conflict do nothing;\n end if;\nend $evolution_apply$;`,
    );
  }
  parts.push(
    readFileSync("supabase/seed.sql", "utf8"),
    "notify pgrst,'reload schema';\ncommit;",
  );
  return parts.join("\n\n") + "\n";
}
